/// `Inwood-207 St (northbound)` or fallback to raw id.
pub fn format_stop_label(stop_id: &str) -> String {
    if stop_id.is_empty() {
        return "—".into();
    }
    let name = stop_name(stop_id);
    let dir = direction_label(stop_id);
    match (name, dir) {
        (Some(name), Some(dir)) => format!("{name} ({dir})"),
        (Some(name), None) => name.to_string(),
        (None, Some(dir)) => format!("{stop_id} ({dir})"),
        (None, None) => stop_id.to_string(),
    }
}

/// Format unix seconds as `Sat Aug 9, 1:42 PM ET` (fixed UTC−4; NYC summer).
pub fn format_unix_et(unix: i64) -> String {
    if unix <= 0 {
        return "—".into();
    }
    let Some(utc) = chrono::DateTime::from_timestamp(unix, 0) else {
        return unix.to_string();
    };
    // Eastern Daylight (UTC−4). Winter EST would be −5; good enough for UI.
    let et = utc - chrono::Duration::hours(4);
    et.format("%a %b %d, %I:%M %p ET").to_string()
}

