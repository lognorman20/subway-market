//! Human-readable MTA stop labels for market UI.

/// Cardinal direction from MTA stop id suffix (`N` / `S`).
pub fn direction_label(stop_id: &str) -> Option<&'static str> {
    match stop_id.chars().last()? {
        'N' => Some("northbound"),
        'S' => Some("southbound"),
        _ => None,
    }
}

